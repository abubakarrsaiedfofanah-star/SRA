-- Student Research Africa: baseline Supabase schema
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null,
  role text not null check (role in ('student', 'teacher', 'lecturer', 'worker', 'admin')),
  country text,
  level text,
  course text,
  status text not null default 'pendingReview',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  question text not null,
  answer text,
  image_url text,
  voice_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.units (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  units jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.questions enable row level security;
alter table public.units enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and status = 'approved'
  );
$$;

create or replace function public.prevent_profile_privilege_escalation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.role <> 'admin' and not public.is_admin()
    and (new.role is distinct from old.role or new.status is distinct from old.status) then
    raise exception 'Only an administrator can change profile role or status';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_privileges on public.profiles;
create trigger protect_profile_privileges
before update on public.profiles
for each row execute function public.prevent_profile_privilege_escalation();

create policy "Users and admins can read profiles" on public.profiles
  for select using (auth.uid() = id or public.is_admin());
create policy "Users can insert their profile" on public.profiles for insert with check (auth.uid() = id);
create policy "Users can update their profile" on public.profiles
  for update using (auth.uid() = id or public.is_admin())
  with check (auth.uid() = id or public.is_admin());
create policy "Admins can delete profiles" on public.profiles for delete using (public.is_admin());
create policy "Users can manage their questions" on public.questions for all using (auth.uid() = student_id) with check (auth.uid() = student_id);
create policy "Users can manage their units" on public.units for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

insert into storage.buckets (id, name, public)
values ('question-media', 'question-media', true)
on conflict (id) do nothing;
